-- Difficulty (0-1): 40% unique letter ratio, 35% letter rarity, 25% length.
create or replace function public.hangman_calculate_word_difficulty(
  word_text text,
  word_locale text default 'en'
)
returns numeric
language plpgsql
stable
set search_path = public
as $$
declare
  word_upper text := upper(word_text);
  word_length int := length(upper(word_text));
  unique_letters int;
  unique_ratio numeric := 0;
  avg_letter_rarity numeric;
  length_score numeric;
begin
  select count(distinct letter_char) into unique_letters
  from regexp_split_to_table(word_upper, '') as letter_char
  where letter_char ~ '[A-ZÑÁÉÍÓÚÜ]';

  if word_length > 0 then
    unique_ratio := unique_letters::numeric / word_length::numeric;
  end if;

  select coalesce(avg(1.0 - coalesce(lf.frequency, 0.5)), 0.5)
  into avg_letter_rarity
  from regexp_split_to_table(word_upper, '') as letter_char
  left join public.hangman_letter_frequencies lf
    on lf.letter = letter_char and lf.locale = word_locale
  where letter_char ~ '[A-ZÑÁÉÍÓÚÜ]';

  length_score := greatest(0.0, least(1.0, (word_length::numeric - 3.0) / 12.0));

  return least(1.0, greatest(0.0,
    unique_ratio * 0.40 + avg_letter_rarity * 0.35 + length_score * 0.25
  ));
end;
$$;

comment on function public.hangman_calculate_word_difficulty(text, text) is
  'Calculates word difficulty (0-1) based on unique letters, length, and letter rarity';

create or replace function public.hangman_trigger_calculate_word_difficulty()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' or new.word <> old.word or new.locale <> old.locale then
    new.difficulty_value := greatest(1, round(
      public.hangman_calculate_word_difficulty(new.word, new.locale) * 100
    ));
  end if;
  return new;
end;
$$;

create trigger hangman_words_calculate_difficulty
  before insert or update on public.hangman_words
  for each row execute function public.hangman_trigger_calculate_word_difficulty();

create or replace function public.hangman_update_all_word_difficulties()
returns table (updated_count integer)
language plpgsql
set search_path = public
as $$
declare
  affected_rows int := 0;
begin
  update public.hangman_words w
  set difficulty_value = greatest(1, round(
    public.hangman_calculate_word_difficulty(w.word, w.locale) * 100
  ));
  get diagnostics affected_rows = row_count;
  return query select affected_rows;
end;
$$;

create or replace function public.hangman_update_word_difficulties_by_locale(
  target_locale text
)
returns table (updated_count integer)
language plpgsql
set search_path = public
as $$
declare
  affected_rows int := 0;
begin
  update public.hangman_words w
  set difficulty_value = greatest(1, round(
    public.hangman_calculate_word_difficulty(w.word, w.locale) * 100
  ))
  where w.locale = target_locale;
  get diagnostics affected_rows = row_count;
  return query select affected_rows;
end;
$$;

create view public.hangman_words_with_tags
with (security_invoker = on) as
select
  w.id,
  w.word,
  w.difficulty_value,
  w.locale,
  w.created_at,
  coalesce(
    array_agg(t.tag order by t.tag) filter (where t.tag is not null),
    array[]::text[]
  ) as tags
from public.hangman_words w
left join public.hangman_word_tags wt on wt.word_id = w.id
left join public.hangman_tags t on t.id = wt.tag_id
group by w.id, w.word, w.difficulty_value, w.locale, w.created_at;

-- Runs as the owner so the leaderboard can read usernames from auth.users.
-- Only the username is taken from auth.users.
create view public.hangman_game_records_with_usernames
with (security_invoker = off) as
select
  gr.id,
  gr.user_id,
  gr.created_at,
  gr.has_timed_mode_enabled,
  gr.difficulty,
  gr.points,
  gr.words,
  gr.time_playing,
  coalesce(au.raw_user_meta_data ->> 'username', 'Player') as username
from public.hangman_game_records gr
left join auth.users au on au.id = gr.user_id;

