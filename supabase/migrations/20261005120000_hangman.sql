-- Hangman: words with tags, difficulty scoring, and the shared leaderboard.
-- Every object uses the hangman_ prefix because the project is shared with
-- Wallet, Family Games, and Habit Tracker.

create type public.hangman_difficulty as enum ('easy', 'medium', 'hard');

-- Letter frequencies (0-1) per locale, used to score word difficulty.
create table public.hangman_letter_frequencies (
  letter character(1) not null,
  locale text not null,
  frequency numeric(3, 2) not null,
  primary key (letter, locale),
  constraint hangman_letter_frequencies_frequency_check
    check (frequency >= 0 and frequency <= 1)
);

comment on table public.hangman_letter_frequencies is
  'Letter frequency data by language for difficulty calculation';

