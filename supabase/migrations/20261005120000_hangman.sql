create table public.hangman_words (
  id bigint generated by default as identity primary key,
  word text not null,
  difficulty_value integer not null,
  locale text not null default 'en',
  created_at timestamptz not null default now(),
  constraint hangman_words_word_locale_unique unique (word, locale),
  constraint hangman_words_difficulty_value_check
    check (difficulty_value >= 1 and difficulty_value <= 100)
);

comment on table public.hangman_words is
  'Words for the Hangman game with difficulty values and locale';

create table public.hangman_tags (
  id bigint generated by default as identity primary key,
  tag text not null,
  locale text not null default 'en',
  created_at timestamptz not null default now(),
  constraint hangman_tags_tag_locale_unique unique (tag, locale)
);

comment on table public.hangman_tags is 'Descriptive tags/hints for words';

create table public.hangman_word_tags (
  word_id bigint not null references public.hangman_words (id) on delete cascade,
  tag_id bigint not null references public.hangman_tags (id) on delete cascade,
  primary key (word_id, tag_id)
);

comment on table public.hangman_word_tags is 'Links words to their tags';

create table public.hangman_game_records (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null default auth.uid()
    references auth.users (id) on delete cascade,
  has_timed_mode_enabled boolean,
  difficulty public.hangman_difficulty,
  points bigint,
  words bigint,
  time_playing bigint
);

