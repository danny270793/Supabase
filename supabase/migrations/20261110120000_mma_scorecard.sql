-- MMA ScoreCard: UFC events, fight cards, fighters and where they come from,
-- scraped from Sherdog. Every object uses the mma_ prefix because the project
-- is shared with the other apps.
--
-- Reference data: everyone (including signed-out users, the app has no
-- sign-in) can read it; only the service role writes it.

create table public.mma_countries (
  id bigint generated by default as identity primary key,
  name text
);

comment on table public.mma_countries is 'Countries of cities (venues and fighter hometowns)';

create table public.mma_cities (
  id bigint generated by default as identity primary key,
  name text,
  country_id bigint not null references public.mma_countries (id)
);

comment on table public.mma_cities is
  'Cities or states as Sherdog writes them (e.g. "Nevada" for Las Vegas venues)';

create table public.mma_locations (
  id bigint generated by default as identity primary key,
  name text,
  city_id bigint not null references public.mma_cities (id)
);

comment on table public.mma_locations is 'Event venues, e.g. "UFC Apex, Las Vegas"';

create table public.mma_categories (
  id bigint generated by default as identity primary key,
  name text not null,
  weight integer
);

comment on table public.mma_categories is 'Weight classes of fights';
comment on column public.mma_categories.weight is 'Weight limit in pounds; null for catchweights';

create table public.mma_referees (
  id bigint generated by default as identity primary key,
  name text not null
);

comment on table public.mma_referees is 'Referees of fights';

create table public.mma_fighters (
  id bigint generated by default as identity primary key,
  name text not null,
  nickname text,
  city_id bigint not null references public.mma_cities (id),
  birthday date,
  died date,
  height numeric(6, 2),
  weight numeric(6, 2),
  link text not null,
  constraint mma_fighters_link_unique unique (link)
);

comment on table public.mma_fighters is 'Fighters, keyed by their Sherdog page';
comment on column public.mma_fighters.city_id is 'Hometown';
comment on column public.mma_fighters.height is 'Height in centimeters (0 when unknown)';
comment on column public.mma_fighters.weight is 'Weight in kilograms (0 when unknown)';
comment on column public.mma_fighters.link is 'Sherdog fighter page';

create table public.mma_events (
  id bigint generated by default as identity primary key,
  name text not null,
  matchup text,
  date date not null,
  link text not null,
  status text not null,
  location_id bigint not null references public.mma_locations (id),
  constraint mma_events_link_unique unique (link),
  constraint mma_events_status_check check (status in ('upcoming', 'past'))
);

comment on table public.mma_events is 'Events (cards), keyed by their Sherdog page';
comment on column public.mma_events.matchup is 'Headline bout, e.g. "Gane vs. Hokit"';
comment on column public.mma_events.link is 'Sherdog event page';

create table public.mma_fights (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.mma_events (id) on delete cascade,
  position integer not null,
  category_id bigint references public.mma_categories (id),
  fighter_one_id bigint not null references public.mma_fighters (id),
  fighter_two_id bigint not null references public.mma_fighters (id),
  referee_id bigint references public.mma_referees (id),
  main_event boolean not null default false,
  title_fight boolean not null default false,
  status text not null,
  method text,
  decision text,
  round smallint,
  time_seconds integer,
  winner smallint,
  constraint mma_fights_status_check check (status in ('done', 'pending')),
  constraint mma_fights_round_check check (round between 1 and 5),
  constraint mma_fights_time_seconds_check check (time_seconds >= 0),
  constraint mma_fights_winner_check check (winner in (1, 2)),
  constraint mma_fights_different_fighters_check check (fighter_one_id <> fighter_two_id)
);

comment on table public.mma_fights is 'Bouts of an event';
comment on column public.mma_fights.position is 'Order on the card as listed by Sherdog';
comment on column public.mma_fights.status is 'done once the bout happened, pending before';
comment on column public.mma_fights.method is 'Finer result, e.g. "Unanimous", "Punches", "Rear-Naked Choke"';
comment on column public.mma_fights.decision is 'Result kind, e.g. "Decision", "KO", "Submission", "Draw"';
comment on column public.mma_fights.round is 'Round the bout ended in';
comment on column public.mma_fights.time_seconds is 'Time into the final round, in seconds';
comment on column public.mma_fights.winner is
  '1 = fighter one won, 2 = fighter two won, null = draw, no contest or not fought yet';

create index mma_cities_country_id_idx on public.mma_cities (country_id);
create index mma_locations_city_id_idx on public.mma_locations (city_id);
create index mma_fighters_city_id_idx on public.mma_fighters (city_id);
create index mma_events_location_id_idx on public.mma_events (location_id);
create index mma_events_date_idx on public.mma_events (date desc);
create index mma_fights_event_id_idx on public.mma_fights (event_id, position);
create index mma_fights_category_id_idx on public.mma_fights (category_id);
create index mma_fights_referee_id_idx on public.mma_fights (referee_id);
create index mma_fights_fighter_one_id_idx on public.mma_fights (fighter_one_id);
create index mma_fights_fighter_two_id_idx on public.mma_fights (fighter_two_id);

